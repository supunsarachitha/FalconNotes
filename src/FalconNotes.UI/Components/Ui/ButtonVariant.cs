namespace FalconNotes.UI.Components.Ui;

/// <summary>The looks a <see cref="Button"/> can have.</summary>
public enum ButtonVariant
{
    /// <summary>Filled with the accent colour: the screen's main action.</summary>
    Primary,

    /// <summary>Outlined on white.</summary>
    Secondary,

    /// <summary>Text only, with a background on hover.</summary>
    Ghost,

    /// <summary>Filled red: deletes or erases something.</summary>
    Danger,
}
